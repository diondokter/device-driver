    #[test]
    fn it_decodes() {
        let bytes = [1, 2, 0, 0, 0, 0, 4, 5];

        let mut res: Vec<u8> = Vec::new();

        let mut encoder = Encoder::new();
        encoder.start_frame(|byte| res.push(byte));
        encoder.write(&bytes, |byte| res.push(byte));
        encoder.end_frame(|byte| res.push(byte));

        let mut encoder = Encoder::new();
        encoder.start_frame(|byte| res.push(byte));
        encoder.write(&bytes, |byte| res.push(byte));
        encoder.end_frame(|byte| res.push(byte));

        for frame in res.split(|byte| *byte == 0) {
            if frame.is_empty() {
                continue;
            }

            let decoded_bytes = rzcobs_decode(&frame);
            assert_eq!(&decoded_bytes.unwrap()[..bytes.len()], bytes);
        }
    }
