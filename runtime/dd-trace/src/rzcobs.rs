// Standard COBS/rCOBS:
//   00000000 => end of frame
//   nnnnnnnn => output n-1 bytes from stream, output 0x00
//   11111111 => output 254 bytes from stream
//
// zCOBS/rzCOBS:
//   00000000 => end of frame
//   0xxxxxxx => foreach x from LSB to MSB: if x=0 output 1 byte from stream, if x=1 output 0x00
//   1nnnnnnn => output n+7 bytes from stream, output 0x00
//   11111111 => output 134 bytes from stream

pub(crate) struct Encoder {
    run: u8,
    zeros: u8,
}

impl Encoder {
    pub const fn new() -> Self {
        Self { run: 0, zeros: 0 }
    }

    pub fn start_frame(&mut self, mut write_byte: impl FnMut(u8)) {
        // Write a frame-separator at the very beginning. This allows the
        // decoder to correctly decode the first frame if a previous boot had left a
        // partly-written frame.
        write_byte(0x00);
    }

    pub fn end_frame(&mut self, mut write_byte: impl FnMut(u8)) {
        // Finish writing the previous symbol if needed.
        match self.run {
            0 => {}
            1..=6 => write_byte((self.zeros | (0xFF << self.run)) & 0x7F),
            _ => write_byte((self.run - 7) | 0x80),
        }

        // Write frame-separator.
        write_byte(0x00);
    }

    pub fn write(&mut self, data: &[u8], mut write_byte: impl FnMut(u8)) {
        for &byte in data {
            if self.run < 7 {
                if byte == 0 {
                    self.zeros |= 1 << self.run;
                } else {
                    write_byte(byte);
                }

                self.run += 1;
                if self.run == 7 && self.zeros != 0x00 {
                    write_byte(self.zeros);
                    self.run = 0;
                    self.zeros = 0;
                }
            } else if byte == 0 {
                write_byte((self.run - 7) | 0x80);
                self.run = 0;
                self.zeros = 0;
            } else {
                write_byte(byte);
                self.run += 1;
                if self.run == 134 {
                    write_byte(0xFF);
                    self.run = 0;
                    self.zeros = 0;
                }
            }
        }
    }
}

/// Decode a full message.
///
/// `data` must be a full rzCOBS encoded message. Decoding partial
/// messages is not possible. `data` must NOT include any `0x00` separator byte.
///
/// Will always output a multiple of 7 bytes. The bytes not part of the original message padded 0 at the end.
#[cfg(any(feature = "std", test))]
pub fn rzcobs_decode(data: &[u8]) -> Result<Vec<u8>, DecodeError> {
    let mut res = vec![];
    let mut data = data.iter().rev().cloned();
    while let Some(x) = data.next() {
        match x {
            0 => return Err(DecodeError),
            0x01..=0x7f => {
                for i in 0..7 {
                    if x & (1 << (6 - i)) == 0 {
                        res.push(data.next().ok_or(DecodeError)?);
                    } else {
                        res.push(0);
                    }
                }
            }
            0x80..=0xfe => {
                let n = (x & 0x7f) + 7;
                res.push(0);
                for _ in 0..n {
                    res.push(data.next().ok_or(DecodeError)?);
                }
            }
            0xff => {
                for _ in 0..134 {
                    res.push(data.next().ok_or(DecodeError)?);
                }
            }
        }
    }

    res.reverse();
    Ok(res)
}

#[cfg(any(feature = "std", test))]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct DecodeError;

#[cfg(any(feature = "std", test))]
impl std::error::Error for DecodeError {}

#[cfg(any(feature = "std", test))]
impl std::fmt::Display for DecodeError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "rzcobs decode error")
    }
}

